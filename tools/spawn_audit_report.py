"""Builds docs/SPAWN_AUDIT.md from the rows of game/tests/spawn_audit_check.gd (--out=<file.tsv>, one per pack).

    python tools/spawn_audit_report.py rows_es1.tsv rows_tribes2.tsv ... [-o docs/SPAWN_AUDIT.md]

Row: pack, map, point label, "x y z", unit, result, reason. Result: ok | fail:<kind> | exception:<kind> | not_for_herc:<kind>.
Only the rows that are not ok are listed one by one; the passing ones are counted per map.
"""
import argparse
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EXCEPTIONS = os.path.join(ROOT, "game", "tests", "spawn_audit_exceptions.json")
PACK_ORDER = ["es1", "es2", "bd", "starsiege", "tribes", "tribes2", "tribes_aa", "tribes_v"]
PACK_NAMES = {"es1": "Earthsiege 1", "es2": "Earthsiege 2", "bd": "Battledrome arenas", "starsiege": "Starsiege",
              "tribes": "Tribes 1", "tribes2": "Tribes 2 (with Varuna's Fall)", "tribes_aa": "Tribes: Aerial Assault",
              "tribes_v": "Tribes: Vengeance"}


def read_rows(paths):
    """{(pack, map): [row]}: the rows of every map, a map found in several files (a re-run) keeping those of the last."""
    by_map = collections.OrderedDict()
    for p in paths:
        fresh = collections.OrderedDict()
        with open(p, encoding="utf-8") as f:
            for line in f:
                parts = line.rstrip("\n").split("\t")
                if len(parts) >= 6:
                    parts += [""] * (7 - len(parts))
                    fresh.setdefault((parts[0], parts[1]), []).append(parts[:7])
        by_map.update(fresh)
    return by_map


def classify(result):
    return result.split(":")[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rows", nargs="+")
    ap.add_argument("-o", "--out", default=os.path.join(ROOT, "docs", "SPAWN_AUDIT.md"))
    args = ap.parse_args()
    by_map = read_rows(args.rows)
    exceptions = {}
    if os.path.exists(EXCEPTIONS):
        with open(EXCEPTIONS, encoding="utf-8") as f:
            exceptions = json.load(f)
    for rs in by_map.values():   # the test's judgement: a failure the exceptions file names is an exception
        for r in rs:
            key = "%s|%s|%s" % (r[1], r[2], r[4])
            if r[5].startswith("fail:") and key in exceptions:
                r[5] = "exception:" + r[5].split(":", 1)[1]
                r[6] = "%s [exception: %s]" % (r[6], exceptions[key])
    out = ["# Spawn audit", "",
           "Generated by `tools/spawn_audit_report.py` from `game/tests/spawn_audit_check.gd` (a light soldier, the large Herc and, on",
           "Tribes maps, the pack's largest ground vehicle set down at every spawn point of every map of every installed pack).",
           "Re-run per pack:", "",
           "    godot --headless --audio-driver Dummy --path game res://tests/spawn_audit_check.tscn -- --only=<pack> --out=rows.tsv", "",
           "A unit **fails** when it starts inside collision (penetration deeper than 0.35 m for a soldier, 1 m for a vehicle), is set",
           "down more than 5 m above its floor, falls through the world, is still falling after 90 physics frames, rests outside the",
           "playable area, dies, or cannot move 2 m in any of four headings (150 frames each). Campaign missions (`mission:` rows) are started in a real Battle",
           "and the places their runtime put the player and the ground units at (a flyer or a later wave is not part of it; `n/a` rows have none)",
           "are audited in the battle's own world. A Herc that fails on a soldiers-only",
           "infantry drop point is reported as `not_for_herc` (the game never starts a Herc there: MapBuilder gives Hercs the",
           "ground next to such a base). Points: Herc / pad / team / infantry starts (MapBuilder), Battledrome pads and ring",
           "(ArenaBuilder), and on the maps an extraction raid is played on: exfil zones, loot areas, insertion points, Varuna's",
           "site and site spawn areas, the Cybrid siege's gate spots. The soldier is also set down the way bots and extraction",
           "do (`BattleInfantry.make_ground_point`) where that differs from a respawn at the start (`bot soldier`).", ""]
    out += ["## Root causes found and fixed by the audit", "",
            "- `SpawnClearance` counted collision shapes a prop frees at the end of the frame (props built without collision), so spawns were",
            "  lifted onto invisible floors (Aerial Assault Mission04: a start hanging 12 m up). It ignores them now.",
            "- `SpawnClearance.make_clear_origin` climbed hillsides: terrain trimesh slopes rising beside a vehicle counted as obstacles (Cybrid gate",
            "  spots 13 m in the air). The terrain only counts over the spawn point itself.",
            "- `MapBuilder.make_spawn_transform`: a drop point the file puts in the air or buried in the heightfield now stands on what is really under",
            "  it (`SpawnClearance.make_supported_origin`: a building's floor, else the terrain), also for Aerial Assault's `indoor: false` points",
            "  inside towers and for starts over a hole with a deck under them.",
            "- Herc starts under cover or on a slope move to the nearest open level ground (`make_level_ground_origin`), as the infantry fallbacks did.",
            "- Terrain height for standing: `MapTerrain.make_collision_height` is the height of the collision triangle (Earthsiege 2's 64 m squares",
            "  differ from the bilinear height by 5 m: soldiers fell through the world, Hercs started 6 m up). Used by `BattleInfantry.make_ground_point`,",
            "  the Earthsiege 2 mission units and `SpawnClearance`.",
            "- `BattleInfantry.make_ground_point`: a start that would drop more than 4 m is set on the floor below (Tribes 2 training drop points 8-16 m",
            "  up); a drop point inside a base keeps its floor instead of being lifted to the hole's rim.",
            "- Starsiege mission starts (`SSStartPositions`) stood in the air or inside the terrain (CA0 30 m up, CA2 17 m inside a hill).",
            "- `MapBounds` grows to contain every start (the importers' areas are the bounding box of the objects: a start on the edge counted as outside).",
            "- Extraction: squad / site / gate spots (`ExtractionSquads.make_place_around`, shared with the siege gates) now choose level ground for",
            "  vehicles and standable ground for soldiers, inside the map's area, spreading wider when none is near; Cybrid gate spots no longer keep the",
            "  gate's height.",
            "- The Herc / vehicle level-ground search (`SpawnClearance.make_level_ground_origin`) skips candidates over a terrain hole (they hung at the",
            "  height of the base start: Tribes 1 King Under the Hill, Aerial Assault Underhill), judges building floors as well as the heightfield (a",
            "  slope or a drop on a base's own floor: Tribes 2 Talus), rejects places a wall or pillar stands within 3.2 m of, and puts candidates 0.5 m",
            "  above the ground when the start lies below the surface (inside a base), where the terrain's own slope counted as cover.",
            "- A soldier's drop point under a deck lower than his body stands on the deck (`SpawnClearance.make_headroom_origin`: Tribes 2 Training4).",
            "- Vehicle pads face open ground (`SpawnClearance.make_open_facing`), as the Herc starts do (Tribes 2 Recalescence pad 2).", ""]
    # summary per pack
    out += ["## Summary", "", "| Pack | Maps | Points | Probes | ok | not for Hercs | exceptions | failures |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    packs = sorted({k[0] for k in by_map}, key=lambda p: PACK_ORDER.index(p) if p in PACK_ORDER else 99)
    total = collections.Counter()
    for pack in packs:
        c = collections.Counter()
        points = set()
        maps = 0
        for (pk, mp), rs in by_map.items():
            if pk != pack:
                continue
            maps += 1
            for r in rs:
                c[classify(r[5])] += 1
                points.add((mp, r[2]))
        n = sum(c.values())
        out.append("| %s | %d | %d | %d | %d | %d | %d | %d |" % (PACK_NAMES.get(pack, pack), maps, len(points), n, c["ok"],
                                                               c["not_for_herc"], c["exception"], c["fail"]))
        total.update(c)
        total["maps"] += maps
        total["points"] += len(points)
    out.append("| **All** | %d | %d | %d | %d | %d | %d | %d |" % (total["maps"], total["points"], sum(total[k] for k in ("ok", "not_for_herc", "exception", "fail")),
                                                               total["ok"], total["not_for_herc"], total["exception"], total["fail"]))
    out.append("")
    if exceptions:
        out += ["## Documented exceptions", "", "From `game/tests/spawn_audit_exceptions.json` (key `map|point|unit`):", ""]
        for k, why in exceptions.items():
            out.append("- `%s`: %s" % (k, why))
        out.append("")
    # per map
    for pack in packs:
        out += ["## " + PACK_NAMES.get(pack, pack), "", "| Map | Points | ok | not for Hercs | exceptions | failures |", "|---|---:|---:|---:|---:|---:|"]
        details = []
        for (pk, mp), rs in by_map.items():
            if pk != pack:
                continue
            c = collections.Counter(classify(r[5]) for r in rs)
            pts = len({r[2] for r in rs})
            out.append("| %s | %d | %d | %d | %d | %d |" % (mp, pts, c["ok"], c["not_for_herc"], c["exception"], c["fail"]))
            bad = [r for r in rs if r[5] != "ok"]
            if bad:
                details.append((mp, bad))
        out.append("")
        for mp, bad in details:
            out += ["### " + mp, "", "| Point | Position | Unit | Result | Reason |", "|---|---|---|---|---|"]
            for r in bad:
                out.append("| %s | %s | %s | %s | %s |" % (r[2], r[3], r[4], r[5], r[6]))
            out.append("")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s (%d maps)" % (args.out, len(by_map)))


if __name__ == "__main__":
    sys.exit(main())
